import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';

const server=createServer(async(_request,response)=>{response.setHeader('Content-Type','text/html;charset=utf-8');response.end(await readFile('dist/index.html'));});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
let browser;
try {
  browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
  const page=await browser.newPage(), external=[];
  page.on('request',request=>{if(!request.url().startsWith(`http://127.0.0.1:${server.address().port}/`))external.push(request.url());});
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.locator('#ai-review-status').waitFor({state:'attached'});
  assert.equal(await page.locator('#ai-mode,#ai-review-open,#proof-toggle,#check-now').count(),0,'no modal review controls');
  // The app persists the old report during beforeunload, so inject the synthetic
  // fixture into the next page's workspace read instead of racing that save.
  await page.addInitScript(()=>{
    const original=Storage.prototype.getItem;let injected=false;
    Storage.prototype.getItem=function(key){
      const value=original.call(this,key);if(key!=='mri-report-studio.workspace.v1'||injected||!value)return value;
      const workspace=JSON.parse(value),report=workspace.reports.find(item=>item.id===workspace.activeId)??workspace.reports[0];
      const section=report.doc.content.find(node=>node.attrs?.id==='description');
      const visit=node=>{if(node.type==='text'){node.text='[[СИНТЕТИЧЕСКИЙ_МАРКЕР]] Ошибкка  ТЕСТ';return true;}for(const child of node.content??[])if(visit(child))return true;return false;};
      if(!visit(section))throw new Error('Description fixture has no text node');if(!workspace.reports.some(r=>r.id==='synthetic-tab-2'))workspace.reports.push({...structuredClone(report),id:'synthetic-tab-2'});injected=true;return JSON.stringify(workspace);
    };
  });
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#ai-review-status')?.hasAttribute('aria-busy')&&Boolean(document.querySelector('#ai-review-status')?.textContent));
  const marks=page.locator('.ai-review-underline').filter({hasText:'СИНТЕТИЧЕСКИЙ_МАРКЕР'});
  await marks.first().waitFor({state:'visible',timeout:5000});
  assert.equal(await page.locator('.ai-review-card').count(),0);
  assert.equal(await page.locator('[role="dialog"]').count(),0,'contextual results remain non-modal');
  assert.equal(await marks.first().getAttribute('tabindex'),null,'review underline does not intercept editor keyboard navigation');
  assert.equal(await marks.first().getAttribute('role'),'mark');
  await marks.first().hover();
  assert.equal(await page.locator('.ai-review-card').count(),0,'hover never opens the review menu');
  await page.locator('[data-section-id="header"]').first().click({button:'right'});
  assert.equal(await page.locator('.ai-review-card').count(),0,'right click outside a finding keeps the normal context behavior');
  await marks.first().click();
  assert.equal(await page.locator('.ai-review-card').count(),0,'left click only places the editor cursor/selects text');
  await marks.first().dblclick();
  assert.equal(await page.locator('.ai-review-card').count(),0,'double click selects a word without opening a review card');
  assert.ok(await page.evaluate(()=>getSelection()?.isCollapsed===false),'double click retains normal word selection');
  await marks.first().click({button:'right'});
  assert.equal(await page.locator('.ai-review-card').count(),1,'right click opens the review menu');
  assert.equal(await page.locator('.proof-popup').count(),0,'AI Review and spelling popups never overlap');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.ai-review-card').count(),0,'Escape closes the contextual card');
  await marks.first().click({button:'right'});
  await page.locator('#document-name').click();
  await page.waitForFunction(()=>!document.querySelector('.ai-review-card'),null,{timeout:2000});
  await marks.first().click({button:'right'});
  await page.locator('[data-report-select="synthetic-tab-2"]').click();
  assert.equal(await page.locator('.ai-review-card').count(),0,'switching tabs closes the review menu');
  await page.locator('.report-tab-select').first().click();
  await marks.first().waitFor();
  await page.locator('.ai-review-panel summary').click();
  const panelIssue=page.locator('.ai-review-finding').first();
  await panelIssue.focus();await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelectorAll('.ai-review-card').length===1,null,{timeout:2000});
  assert.equal(await page.locator('.ai-review-card').count(),1,'keyboard activation of a side-panel finding opens its contextual card');
  await page.locator('.ai-review-card-close').click();
  await marks.first().click({button:'right'});
  assert.equal(await page.locator('.ai-review-card').count(),1,'right click opens the contextual menu');
  const cardText=await page.locator('.ai-review-card').innerText();assert.ok(cardText.includes('Незаполненный маркер'),cardText);
  const textBeforeReject=await page.locator('.report-content').innerText();
  const storedDocBeforeReject=await page.evaluate(()=>JSON.stringify(JSON.parse(localStorage.getItem('mri-report-studio.workspace.v1')||'{}').reports?.[0]?.doc));
  await page.keyboard.press('Tab');
  assert.ok(await page.locator('.ai-review-card').count()<=1);
  await page.locator('.ai-review-card button').filter({hasText:'Отклонить'}).click();
  assert.equal(await page.locator('.ai-review-underline').filter({hasText:'СИНТЕТИЧЕСКИЙ_МАРКЕР'}).count(),0,'rejecting a clinical comment removes only its temporary decoration');
  assert.ok(await page.locator('.ai-review-underline').count()>0,'unrelated review findings remain visible');
  assert.equal(await page.locator('.report-content').innerText(),textBeforeReject,'rejecting does not edit report text');
  const state=await page.evaluate(()=>({doc:JSON.stringify(JSON.parse(localStorage.getItem('mri-report-studio.workspace.v1')||'{}').reports?.[0]?.doc),keys:Object.keys(localStorage)}));
  assert.equal(state.doc,storedDocBeforeReject,'review decorations and rejection do not persist into the report document');
  assert.ok(!state.doc.includes('ai-review-underline'));
  assert.ok(!state.keys.some(key=>key.includes('patient-name')));
  await page.waitForFunction(()=>!document.querySelector('#ai-review-status')?.hasAttribute('aria-busy')&&Boolean(document.querySelector('#ai-review-status')?.textContent));
  assert.equal(await page.locator('.ai-review-underline').filter({hasText:'СИНТЕТИЧЕСКИЙ_МАРКЕР'}).count(),0,'rejected unchanged finding stays dismissed for this open document');
  await page.waitForFunction(()=>!document.querySelector('#ai-review-status')?.hasAttribute('aria-busy')&&Boolean(document.querySelector('#ai-review-status')?.textContent));
  const firstTab=await page.evaluate(()=>JSON.parse(localStorage.getItem('mri-report-studio.workspace.v1')).activeId);
  await page.locator('[data-report-select="synthetic-tab-2"]').click();
  await page.locator('.ai-review-underline').filter({hasText:'СИНТЕТИЧЕСКИЙ_МАРКЕР'}).first().waitFor();
  assert.ok(await page.locator('.ai-review-underline').filter({hasText:'СИНТЕТИЧЕСКИЙ_МАРКЕР'}).count(),'other document has independent rejection state');
  await page.locator(`[data-report-select="${firstTab}"]`).click();
  await page.waitForFunction(()=>Boolean(document.querySelector('#ai-review-status')?.textContent)&&!document.querySelector('#ai-review-status').hasAttribute('aria-busy'));
  assert.equal(await page.locator('.ai-review-underline').filter({hasText:'СИНТЕТИЧЕСКИЙ_МАРКЕР'}).count(),0,'rejection stays scoped to first document');
  const punctuation=page.locator('.ai-review-underline.ai-review-punctuation').first();
  await punctuation.waitFor({state:'visible',timeout:5000});
  await punctuation.click({button:'right'});
  assert.equal(await page.locator('.ai-review-card button').filter({hasText:'Заменить'}).count(),1,'safe punctuation correction offers explicit replacement');
  await page.locator('.ai-review-card button').filter({hasText:'Заменить'}).click();
  assert.match(await page.locator('.report-content').innerText(),/Ошибкка ТЕСТ/,'punctuation replacement changes spacing only');
  await page.keyboard.press('Control+z');
  assert.match(await page.locator('.report-content').innerText(),/Ошибкка  ТЕСТ/,'Undo restores original spacing');
  await page.keyboard.press('Control+y');
  assert.match(await page.locator('.report-content').innerText(),/Ошибкка ТЕСТ/,'Redo restores accepted spacing correction');
  await page.keyboard.press('Control+z');
  await page.waitForFunction(()=>!document.querySelector('#ai-review-status')?.hasAttribute('aria-busy')&&Boolean(document.querySelector('#ai-review-status')?.textContent));
  const spelling=page.locator('.ai-review-underline.ai-review-spelling').filter({hasText:'Ошибкка'});
  await spelling.first().waitFor({state:'visible',timeout:5000});
  await spelling.first().click({button:'right'});
  await page.locator('.ai-review-card details').first().evaluate(el=>el.open=true);
  assert.ok(await page.locator('.ai-review-card').innerText().then(text=>text.includes('Ошибкка')));
  await page.getByRole('button',{name:'Запомнить термин'}).click();
  assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('mri-report-studio.dictionary.v1')||'[]').includes('ошибкка')),'remembered term is stored in the separate personal dictionary');
  await page.locator('#settings').click();
  await page.locator('#dictionary-settings').click();
  const words=page.locator('#personal-words');
  const withoutRemembered=(await words.inputValue()).split(/\s+/).filter(word=>word.toLocaleLowerCase('ru')!=='ошибкка').join('\n');
  await words.fill(withoutRemembered);
  await page.locator('#save-dictionary').click();
  assert.ok(!(await page.evaluate(()=>JSON.parse(localStorage.getItem('mri-report-studio.dictionary.v1')||'[]').includes('ошибкка'))),'user can remove a remembered term');
  await page.reload();
  await page.locator('#ai-review-status').waitFor({state:'attached'});
  assert.ok(!(await page.evaluate(()=>JSON.parse(localStorage.getItem('mri-report-studio.dictionary.v1')||'[]').includes('ошибкка'))),'dictionary deletion survives restart');
  await page.locator('[data-section-id="description"]').first().evaluate(el=>{el.closest('[contenteditable]').focus();const range=document.createRange();range.selectNodeContents(el.firstElementChild);range.collapse(false);const selection=getSelection();selection.removeAllRanges();selection.addRange(range);});
  await page.keyboard.type(' Ошибкка', {delay:20});
  assert.equal(await page.locator('.ai-review-underline').count(),0,'editing immediately invalidates all old positions');
  await page.locator('.ai-review-spelling').filter({hasText:'Ошибкка'}).first().waitFor({timeout:10000});
  assert.ok(await page.locator('.ai-review-spelling').count(),'debounced analysis runs automatically after edits');
  // P0 regression: DOM caret inside an underlined word, actual keyboard Space.
  // Use native typing to synchronize the editor model rather than mutate stored JSON.
  await page.locator('#editor .ProseMirror').press('Control+End');await page.keyboard.type(' суженсправа');
  await page.locator('.ai-review-spelling').filter({hasText:'суженсправа'}).last().waitFor({timeout:15000});
  await page.locator('.ai-review-spelling').filter({hasText:'суженсправа'}).last().evaluate(el=>{const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);walker.nextNode();const node=walker.currentNode;const range=document.createRange();range.setStart(node,node.textContent.indexOf('суженсправа')+5);range.collapse(true);const selection=getSelection();selection.removeAllRanges();selection.addRange(range);el.closest('[contenteditable]').focus();});
  await page.keyboard.press('Space');assert.equal(await page.locator('.ai-review-card').count(),0,'Space edits and never opens popup');assert.match(await page.locator('#editor').innerText(),/сужен справа/);
  await page.keyboard.press('Control+z');assert.match(await page.locator('#editor').innerText(),/суженсправа/);await page.keyboard.press('Control+y');assert.match(await page.locator('#editor').innerText(),/сужен справа/);
  await page.locator('#editor .ProseMirror').press('End');
  await page.keyboard.press('Enter');assert.equal(await page.locator('.ai-review-card').count(),0,'Enter edits without opening a popup');
  await page.keyboard.press('Backspace');assert.equal(await page.locator('.ai-review-card').count(),0,'Backspace edits without opening a popup');
  await page.keyboard.press('Delete');assert.equal(await page.locator('.ai-review-card').count(),0,'Delete edits without opening a popup');
  await page.keyboard.press('Control+z');
  assert.equal(await page.locator('[data-ai-category]').count(),6);
  assert.deepEqual(external,[]);
  console.log('PASS: automatic all-category contextual review and card, local-only review, rejection, workspace isolation and no network requests.');
} finally { await browser?.close(); await new Promise(resolve=>server.close(resolve)); }
