export const trustedMedicalForms = [...medical.words,...medicalLexicon];
const exact = new Set([...medical.words,...medicalLexicon,...TEMPLATE_PERSONAL_WORDS,'микроангиопатия'].map(normalize));
let recognizer:Promise<(word:string)=>boolean>|undefined;
export function loadMedicalWordRecognizer():Promise<(word:string)=>boolean> {
 return recognizer ??= loadMorphology().then(analyze=>{
  const approved=new Set<string>();
  for(const source of medical.lemmaSources){const parses=analyze(normalize(source));const best=Math.max(0,...parses.map(p=>p.score));for(const parse of parses){if(parseCanIdentifyLemma(parse,source,best)){const lemma=normalizedLemma(parse);if(lemma)approved.add(lemma);}}}
  const cache=new Map<string,boolean>();
  return (word:string)=>{
   const key=normalize(word);if(exact.has(key))return true;
   if(cache.has(key))return cache.get(key)!;
   const parses=analyze(key),best=Math.max(0,...parses.map(p=>p.score));
   const accepted=parses.some(p=>parseCanIdentifyLemma(p,word,best)&&(p.parser==='Dictionary'||approved.has(normalizedLemma(p)??'')));
   if(cache.size>10000)cache.clear();cache.set(key,accepted);return accepted;
  };
 });
}
